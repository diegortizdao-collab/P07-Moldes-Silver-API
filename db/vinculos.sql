-- Vínculos ficha de producto <-> molde del P.07.
-- La ficha NO guarda la posición: la lee en vivo del P.07 a través de este vínculo.
create table if not exists vinculos (
  familia_id    text not null,                                   -- id de la familia en la ficha (F1, F2, ... / N123 para altas rápidas)
  molde_id      integer not null references moldes(id) on delete cascade,
  confirmado    boolean not null default false,                  -- false = sugerido automáticamente, falta confirmar
  origen        text not null default 'manual',                  -- 'manual' | 'sugerido'
  vinculado_por text,
  vinculado_en  timestamptz not null default now(),
  primary key (familia_id, molde_id)
);
create index if not exists vinculos_molde_idx on vinculos (molde_id);

